        /// <summary>Accepts "Dubai" as well as "DXB": the screen stores the code.</summary>
        private static string? EmirateCode(string? value) =>
            value == null ? null
                : Emirates.All.ContainsKey(value.ToUpperInvariant()) ? value.ToUpperInvariant()
                : Emirates.All.FirstOrDefault(x => string.Equals(x.Value, value, StringComparison.OrdinalIgnoreCase)).Key ?? value;

