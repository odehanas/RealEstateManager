using System.Text.Json;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.EntityFrameworkCore;
using RealEstateManager.Data;
using RealEstateManager.Domain;
using RealEstateManager.Models;

namespace RealEstateManager.Services.Assistant
{
    /// <summary>
    /// Changes the assistant can prepare. Propose runs the same checks as the screen and
    /// describes the change; nothing is saved. Execute runs only after the user clicks
    /// Confirm, and calls the same service the screen calls.
    /// </summary>
    public static class AssistantWriteTools
    {
        private static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web);

        public static IEnumerable<AssistantTool> All()
        {
            // ---------------------------------------------------------------- tenant
            yield return new AssistantTool
            {
                Name = "propose_create_tenant",
                Description = "Prepare a new tenant for the user to confirm. The code is generated by the system.",
                Screen = ("Tenants", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("full_name", Schema.Str("Person's or company's name"), true),
                    ("party_type", Schema.Enum("Kind of tenant", PartyTypes.All), false),
                    ("phone", Schema.Str("Mobile or phone"), false),
                    ("email", Schema.Str("Email"), false),
                    ("nationality", Schema.Str("Nationality"), false),
                    ("emirates_id", Schema.Str("Emirates ID number"), false),
                    ("passport_number", Schema.Str("Passport number"), false),
                    ("trade_license_number", Schema.Str("Trade licence, for a business"), false),
                    ("trn", Schema.Str("VAT TRN, for a registered business"), false),
                    ("emirate", Schema.Enum("Emirate code", Emirates.All.Keys.ToArray()), false),
                    ("address", Schema.Str("Address"), false)),
                Propose = async (ctx, args) =>
                {
                    var tenant = TenantFrom(args);
                    var state = new ModelStateDictionary();
                    await ctx.Get<MasterDataCreationService>().ValidateTenantAsync(ctx.CompanyId, tenant, state);
                    if (!state.IsValid) return AssistantProposal.Refused(Errors(state));

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Create tenant \"{tenant.FullName}\" ({tenant.PartyType})" +
                                  Join(tenant.Phone, tenant.Email, tenant.IdNumber != null ? "EID " + tenant.IdNumber : null,
                                       tenant.TradeLicenseNumber != null ? "licence " + tenant.TradeLicenseNumber : null,
                                       tenant.TrnNumber != null ? "TRN " + tenant.TrnNumber : null) +
                                  ". The tenant code is assigned when saved.",
                        Normalized = args
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var tenant = TenantFrom(args);
                    var creation = ctx.Get<MasterDataCreationService>();
                    var state = new ModelStateDictionary();
                    await creation.ValidateTenantAsync(ctx.CompanyId, tenant, state);
                    if (!state.IsValid) return AssistantActionResult.Failed(Errors(state));

                    await creation.CreateTenantAsync(ctx.CompanyId, tenant);
                    return new AssistantActionResult
                    {
                        Ok = true, Reference = tenant.Code, Link = $"/Tenants/Edit/{tenant.Id}",
                        Message = $"Tenant {tenant.Code} {tenant.FullName} created."
                    };
                }
            };

            // ---------------------------------------------------------------- vendor
            yield return new AssistantTool
            {
                Name = "propose_create_vendor",
                Description = "Prepare a new vendor (supplier or contractor) for the user to confirm.",
                Screen = ("Vendors", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("name", Schema.Str("Vendor name"), true),
                    ("service_type", Schema.Str("What they supply, e.g. Plumbing"), false),
                    ("contact_person", Schema.Str("Contact person"), false),
                    ("phone", Schema.Str("Phone"), false),
                    ("email", Schema.Str("Email"), false),
                    ("is_vat_registered", Schema.Bool("Registered for VAT"), false),
                    ("trn", Schema.Str("VAT TRN"), false),
                    ("trade_license_number", Schema.Str("Trade licence"), false)),
                Propose = async (ctx, args) =>
                {
                    var vendor = VendorFrom(args);
                    var state = new ModelStateDictionary();
                    await ctx.Get<MasterDataCreationService>().ValidateVendorAsync(ctx.CompanyId, vendor, state);
                    if (!state.IsValid) return AssistantProposal.Refused(Errors(state));

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Create vendor \"{vendor.Name}\"" +
                                  Join(vendor.ServiceType, vendor.ContactPerson, vendor.Phone, vendor.Email,
                                       vendor.IsVatRegistered ? "VAT registered, TRN " + vendor.TrnNumber : "not VAT registered") +
                                  ". The vendor code is assigned when saved.",
                        Normalized = args
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var vendor = VendorFrom(args);
                    var creation = ctx.Get<MasterDataCreationService>();
                    var state = new ModelStateDictionary();
                    await creation.ValidateVendorAsync(ctx.CompanyId, vendor, state);
                    if (!state.IsValid) return AssistantActionResult.Failed(Errors(state));

                    await creation.CreateVendorAsync(ctx.CompanyId, vendor);
                    return new AssistantActionResult
                    {
                        Ok = true, Reference = vendor.Code, Link = $"/Vendors/Edit/{vendor.Id}",
                        Message = $"Vendor {vendor.Code} {vendor.Name} created."
                    };
                }
            };

            // ---------------------------------------------------------------- customer receipt
            yield return new AssistantTool
            {
                Name = "propose_customer_receipt",
                Description = "Prepare a receipt of money against a posted customer invoice; it is saved and posted when the user confirms.",
                Screen = ("CustomerReceipts", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("invoice_number", Schema.Str("Invoice number"), true),
                    ("amount", Schema.Num("Amount received; default the full balance"), false),
                    ("date", Schema.Date("Receipt date, default today"), false),
                    ("method", Schema.Enum("How it was paid", "Bank", "Cash", "Cheque", "Transfer"), false),
                    ("receipt_number", Schema.Str("Receipt number; leave empty to generate"), false)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "invoice_number");
                    var invoice = await ctx.Db.CustomerInvoices.Include(x => x.Lease).ThenInclude(x => x!.Tenant)
                        .FirstOrDefaultAsync(x => x.InvoiceNumber == number);
                    if (invoice == null) return AssistantProposal.Refused($"No invoice {number}.");

                    var outstanding = invoice.TotalAmount - invoice.AmountPaid;
                    var model = new CustomerReceiptCreateViewModel
                    {
                        CustomerInvoiceId = invoice.Id,
                        Amount = Args.Dec(args, "amount") ?? outstanding,
                        ReceiptDate = Args.Date(args, "date") ?? DateTime.Today,
                        PaymentMethod = Args.Str(args, "method") ?? "Bank",
                        ReceiptNumber = Args.Str(args, "receipt_number")
                    };

                    var errors = await ctx.Get<CustomerReceiptService>().ValidateAsync(ctx.CompanyId, model);
                    if (errors.Count > 0) return AssistantProposal.Refused(string.Join(" ", errors.Select(e => e.Message)));
                    var closed = await ClosedPeriodMessageAsync(ctx.Db, model.ReceiptDate, "A customer receipt");
                    if (closed != null) return AssistantProposal.Refused(closed);

                    var warnings = new List<string>();
                    if (model.Amount < outstanding)
                        warnings.Add($"Part payment: {outstanding - model.Amount:N2} {ctx.Currency} will remain due on the invoice.");

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Receive {model.Amount:N2} {ctx.Currency} by {model.PaymentMethod} on {model.ReceiptDate:dd/MM/yyyy} " +
                                  $"against invoice {invoice.InvoiceNumber} ({invoice.Lease?.Tenant?.FullName}, balance {outstanding:N2}), " +
                                  "and post it to the accounts.",
                        Warnings = warnings,
                        Normalized = model
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var model = args.Deserialize<CustomerReceiptCreateViewModel>(Json)!;
                    var service = ctx.Get<CustomerReceiptService>();
                    var errors = await service.ValidateAsync(ctx.CompanyId, model);
                    if (errors.Count > 0) return AssistantActionResult.Failed(string.Join(" ", errors.Select(e => e.Message)));

                    try
                    {
                        var result = await service.CreateAsync(ctx.CompanyId, model);
                        var entry = await JournalNumberAsync(ctx.Db, result.Receipt.JournalEntryId);
                        return new AssistantActionResult
                        {
                            Ok = true, Reference = result.Receipt.ReceiptNumber, Link = "/CustomerReceipts", JournalEntryNumber = entry,
                            Message = result.NotPostedReason == null
                                ? $"Receipt {result.Receipt.ReceiptNumber} saved and posted."
                                : $"Receipt {result.Receipt.ReceiptNumber} was saved as a draft but not posted: {result.NotPostedReason}"
                        };
                    }
                    catch (Exception ex)
                    {
                        return AssistantActionResult.Failed($"The receipt could not be posted, so nothing was saved. {ex.Message}");
                    }
                }
            };

            // ---------------------------------------------------------------- clear PDC
            yield return new AssistantTool
            {
                Name = "propose_clear_pdc",
                Description = "Prepare clearing a post-dated cheque the bank has honoured; the clearance is posted when the user confirms.",
                Screen = ("PdcReceipts", "Clear"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("cheque_number", Schema.Str("Cheque number"), true),
                    ("cleared_date", Schema.Date("Date the bank honoured it, default today"), false)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "cheque_number");
                    var matches = await ctx.Db.PdcReceipts.Include(x => x.Lease).ThenInclude(x => x!.Tenant)
                        .Where(x => x.ChequeNumber == number && x.Status != "Cleared" && x.Status != "Cancelled").ToListAsync();
                    if (matches.Count == 0) return AssistantProposal.Refused($"No uncleared cheque number {number}.");
                    if (matches.Count > 1) return AssistantProposal.Refused($"{matches.Count} uncleared cheques have number {number}; clear it from the PDC screen.");

                    var pdc = matches[0];
                    var date = Args.Date(args, "cleared_date") ?? DateTime.Today;
                    var errors = PdcService.CheckClearance(pdc, date);
                    if (errors.Count > 0) return AssistantProposal.Refused(string.Join(" ", errors.Select(e => e.Message)));
                    var closed = await ClosedPeriodMessageAsync(ctx.Db, date, "A cheque clearance");
                    if (closed != null) return AssistantProposal.Refused(closed);

                    var warnings = new List<string>();
                    var early = PdcService.EarlyClearanceWarning(pdc, date);
                    if (early != null) warnings.Add(early + " Confirming goes ahead anyway.");

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Clear cheque {pdc.ChequeNumber} ({pdc.BankName}) of {pdc.Amount:N2} {ctx.Currency} from " +
                                  $"{pdc.Lease?.Tenant?.FullName}, contract {pdc.Lease?.ContractNumber}, dated {pdc.ChequeDate:dd/MM/yyyy}, " +
                                  $"as cleared on {date:dd/MM/yyyy}, and post the cash entry.",
                        Warnings = warnings,
                        Normalized = new { pdcId = pdc.Id, clearedDate = date }
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var pdcId = args.GetProperty("pdcId").GetInt32();
                    var date = args.GetProperty("clearedDate").GetDateTime();
                    var pdc = await ctx.Db.PdcReceipts.FirstOrDefaultAsync(x => x.Id == pdcId);
                    if (pdc == null) return AssistantActionResult.Failed("The cheque was not found.");
                    var errors = PdcService.CheckClearance(pdc, date);
                    if (errors.Count > 0) return AssistantActionResult.Failed(string.Join(" ", errors.Select(e => e.Message)));

                    try
                    {
                        var journal = await ctx.Get<PdcService>().ClearPdcAsync(pdc.Id, date);
                        var notPosted = await ctx.Get<JournalWorkflowService>().PostNewEntryAsync(journal.Id);
                        return new AssistantActionResult
                        {
                            Ok = true, Reference = pdc.ChequeNumber, Link = "/PdcReceipts", JournalEntryNumber = journal.EntryNumber,
                            Message = notPosted == null
                                ? $"Cheque {pdc.ChequeNumber} cleared and posted."
                                : $"Cheque {pdc.ChequeNumber} was cleared as a draft but not posted: {notPosted}"
                        };
                    }
                    catch (Exception ex)
                    {
                        return AssistantActionResult.Failed(ex.Message);
                    }
                }
            };

            // ---------------------------------------------------------------- manual journal
            yield return new AssistantTool
            {
                Name = "propose_manual_journal",
                Description = "Prepare a DRAFT manual journal (debits must equal credits). It is saved as a draft when confirmed; posting is a separate step.",
                Screen = ("ManualJournals", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("date", Schema.Date("Entry date"), true),
                    ("description", Schema.Str("What the entry is for"), true),
                    ("reference", Schema.Str("Reference"), false),
                    ("lines", Schema.Array("At least two lines",
                        Schema.Object(
                            ("account", Schema.Str("Account code"), true),
                            ("debit", Schema.Num("Debit amount, or 0"), false),
                            ("credit", Schema.Num("Credit amount, or 0"), false),
                            ("description", Schema.Str("Line description"), false),
                            ("unit", Schema.Str("Unit number as cost centre, optional"), false))), true)),
                Propose = async (ctx, args) =>
                {
                    var model = new ManualJournalEntryViewModel
                    {
                        EntryDate = Args.Date(args, "date") ?? throw new AssistantArgumentException("'date' is required."),
                        Description = Args.Required(args, "description"),
                        ReferenceNumber = Args.Str(args, "reference")
                    };

                    if (!args.TryGetProperty("lines", out var lines) || lines.ValueKind != JsonValueKind.Array)
                        return AssistantProposal.Refused("Give the journal lines.");

                    var described = new List<string>();
                    foreach (var line in lines.EnumerateArray().Take(30))
                    {
                        var (account, error) = await AssistantReadTools.ResolveAccountAsync(ctx.Db, Args.Required(line, "account"));
                        if (account == null) return AssistantProposal.Refused(error!);
                        if (!account.IsPostable || account.IsGroup || !account.IsActive)
                            return AssistantProposal.Refused($"{account.Code} {account.Name} is a heading or inactive account; choose a postable one.");

                        int? unitId = null;
                        var unitText = Args.Str(line, "unit");
                        if (unitText != null)
                        {
                            var units = await ctx.Db.Units.Where(x => x.UnitNumber == unitText).Select(x => x.Id).Take(2).ToListAsync();
                            if (units.Count != 1) return AssistantProposal.Refused($"Unit '{unitText}' is not unique or not found.");
                            unitId = units[0];
                        }

                        var debit = Args.Dec(line, "debit") ?? 0m;
                        var credit = Args.Dec(line, "credit") ?? 0m;
                        model.Lines.Add(new ManualJournalLineViewModel
                        {
                            AccountId = account.Id, Debit = debit, Credit = credit,
                            LineDescription = Args.Str(line, "description"), UnitId = unitId
                        });
                        described.Add($"{account.Code} {account.Name}: " + (debit > 0 ? $"Dr {debit:N2}" : $"Cr {credit:N2}") +
                                      (unitText != null ? $" (unit {unitText})" : string.Empty));
                    }

                    if (model.Lines.Count < 2) return AssistantProposal.Refused("At least two journal lines are required.");
                    if (model.Lines.Any(l => l.Debit < 0 || l.Credit < 0)) return AssistantProposal.Refused("Debit and credit must not be negative.");
                    if (model.Lines.Any(l => l.Debit > 0 && l.Credit > 0)) return AssistantProposal.Refused("A journal line cannot have both debit and credit.");
                    var dr = model.Lines.Sum(l => l.Debit);
                    var cr = model.Lines.Sum(l => l.Credit);
                    if (dr != cr) return AssistantProposal.Refused($"Journal entry is not balanced: debits {dr:N2}, credits {cr:N2}.");

                    var period = await ctx.Db.AccountingPeriods.FirstOrDefaultAsync(x => x.StartDate <= model.EntryDate.Date && x.EndDate >= model.EntryDate.Date);
                    if (period == null) return AssistantProposal.Refused("No accounting period found for the selected date.");
                    if (period.IsClosed) return AssistantProposal.Refused("The accounting period is closed. Manual journal cannot be posted.");

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Save a DRAFT manual journal dated {model.EntryDate:dd/MM/yyyy}: \"{model.Description}\", " +
                                  $"{dr:N2} {ctx.Currency}. Lines: {string.Join("; ", described)}. It does not affect the accounts until posted.",
                        Normalized = model
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var model = args.Deserialize<ManualJournalEntryViewModel>(Json)!;
                    try
                    {
                        var id = await ctx.Get<ManualJournalService>().CreateManualJournalAsync(model);
                        var number = await JournalNumberAsync(ctx.Db, id);
                        return new AssistantActionResult
                        {
                            Ok = true, Reference = number, JournalEntryNumber = number, Link = "/ManualJournals",
                            Message = $"Draft journal {number} saved. Say if you want it posted."
                        };
                    }
                    catch (Exception ex)
                    {
                        return AssistantActionResult.Failed(ex.Message);
                    }
                }
            };

            // ---------------------------------------------------------------- post journal
            yield return new AssistantTool
            {
                Name = "propose_post_journal",
                Description = "Prepare posting a DRAFT journal entry into the accounts, through the same checks as Journal Inquiry (closed periods, approvals).",
                Screen = ("Journal", "Post"),
                IsWrite = true,
                Parameters = Schema.Object(("entry_number", Schema.Str("Journal entry number"), true)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "entry_number");
                    var entry = await ctx.Db.JournalEntries.Include(x => x.Lines).ThenInclude(x => x.Account)
                        .FirstOrDefaultAsync(x => x.EntryNumber == number);
                    if (entry == null) return AssistantProposal.Refused($"No journal entry {number}.");
                    if (entry.IsPosted) return AssistantProposal.Refused($"{number} is already posted.");
                    var closed = await ClosedPeriodMessageAsync(ctx.Db, entry.EntryDate, "A journal entry");
                    if (closed != null) return AssistantProposal.Refused(closed);

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Post draft {entry.EntryNumber} dated {entry.EntryDate:dd/MM/yyyy} \"{entry.Description}\" " +
                                  $"({entry.Lines.Sum(l => l.Debit):N2} {ctx.Currency}): " +
                                  string.Join("; ", entry.Lines.Take(8).Select(l => $"{l.Account?.Code} " + (l.Debit > 0 ? $"Dr {l.Debit:N2}" : $"Cr {l.Credit:N2}"))) +
                                  ". It goes into the accounts and reports.",
                        Normalized = new { journalEntryId = entry.Id, entryNumber = entry.EntryNumber }
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var id = args.GetProperty("journalEntryId").GetInt32();
                    var number = args.GetProperty("entryNumber").GetString();
                    var result = await ctx.Get<JournalWorkflowService>().PostAsync(id);
                    return new AssistantActionResult
                    {
                        Ok = result.Success, Message = result.Message, Reference = number, JournalEntryNumber = number, Link = "/Journal"
                    };
                }
            };

            // ---------------------------------------------------------------- lease
            yield return new AssistantTool
            {
                Name = "propose_submit_lease",
                Description = "Prepare putting a DRAFT contract forward: sent for approval when the company requires it, otherwise activated. The assistant never approves.",
                Screen = ("Leases", "Submit"),
                IsWrite = true,
                Parameters = Schema.Object(("contract", Schema.Str("Contract number"), true)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "contract");
                    var lease = await ctx.Db.Leases.Include(x => x.Tenant).Include(x => x.Unit).ThenInclude(x => x!.Property)
                        .FirstOrDefaultAsync(x => x.ContractNumber == number);
                    if (lease == null) return AssistantProposal.Refused($"No contract {number}.");
                    if (lease.Status != LeaseStatuses.Draft) return AssistantProposal.Refused($"{number} is {lease.Status}, not a draft.");

                    var workflow = ctx.Get<LeaseWorkflowService>();
                    var clash = await workflow.CheckUnitFreeAsync(lease.Id, lease.UnitId, lease.StartDate, lease.EndDate);
                    if (clash != null) return AssistantProposal.Refused(clash);
                    var needsApproval = await workflow.ApprovalRequiredAsync();

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = (needsApproval ? "Send for approval" : "Activate") +
                                  $" contract {lease.ContractNumber}: {lease.Tenant?.FullName}, unit {lease.Unit?.Property?.Code}/{lease.Unit?.UnitNumber}, " +
                                  $"{lease.StartDate:dd/MM/yyyy} to {lease.EndDate:dd/MM/yyyy}, {lease.AnnualRent:N2} {ctx.Currency} a year." +
                                  (needsApproval ? " Someone else must approve it." : string.Empty),
                        Normalized = new { leaseId = lease.Id, contract = lease.ContractNumber, approval = needsApproval }
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var id = args.GetProperty("leaseId").GetInt32();
                    var contract = args.GetProperty("contract").GetString();
                    var workflow = ctx.Get<LeaseWorkflowService>();
                    var (success, message) = await workflow.ApprovalRequiredAsync()
                        ? await workflow.SubmitAsync(id, ctx.UserId, ctx.UserName)
                        : await workflow.ActivateAsync(id);
                    return new AssistantActionResult { Ok = success, Message = message, Reference = contract, Link = $"/Leases/Edit/{id}" };
                }
            };

            // ---------------------------------------------------------------- service request
            yield return new AssistantTool
            {
                Name = "propose_update_service_request",
                Description = "Prepare a change to a tenant service request: a new status, resolution notes, and/or a reply the tenant sees (or an internal note).",
                Screen = ("ServiceRequests", "UpdateStatus"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("request_number", Schema.Str("Request number"), true),
                    ("status", Schema.Enum("New status", "Acknowledged", "InProgress", "Resolved", "Rejected", "Closed"), false),
                    ("resolution_notes", Schema.Str("Needed to resolve or reject"), false),
                    ("reply", Schema.Str("Message to add"), false),
                    ("internal", Schema.Bool("True: internal note the tenant cannot see"), false)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "request_number");
                    var request = await ctx.Db.TenantServiceRequests.Include(x => x.Tenant).FirstOrDefaultAsync(x => x.RequestNumber == number);
                    if (request == null) return AssistantProposal.Refused($"No service request {number}.");
                    var status = Args.Str(args, "status");
                    var notes = Args.Str(args, "resolution_notes");
                    var reply = Args.Str(args, "reply");
                    var isInternal = Args.Bool(args, "internal");
                    if (status == null && reply == null) return AssistantProposal.Refused("Give a new status or a reply.");
                    if (status is ServiceRequestStatuses.Resolved or ServiceRequestStatuses.Rejected &&
                        string.IsNullOrWhiteSpace(notes) && string.IsNullOrWhiteSpace(request.ResolutionNotes))
                        return AssistantProposal.Refused("Resolution notes are needed to resolve or reject a request.");

                    var parts = new List<string>();
                    if (status != null) parts.Add($"set status to {status}" + (notes != null ? $" with notes \"{notes}\"" : string.Empty));
                    if (reply != null) parts.Add((isInternal ? "add internal note" : "reply to the tenant") + $": \"{reply}\"");
                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Service request {request.RequestNumber} ({request.Subject}, {request.Tenant?.FullName}): {string.Join("; ", parts)}.",
                        Normalized = new { requestId = request.Id, number = request.RequestNumber, status, notes, reply, isInternal }
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var id = args.GetProperty("requestId").GetInt32();
                    var number = args.GetProperty("number").GetString();
                    var service = ctx.Get<ServiceRequestService>();
                    var messages = new List<string>();
                    var status = args.GetProperty("status").GetString();
                    if (status != null)
                    {
                        var (success, message) = await service.UpdateStatusAsync(ctx.CompanyId, id, status,
                            args.GetProperty("notes").GetString(), null, null, ctx.UserId, ctx.UserName);
                        if (!success) return AssistantActionResult.Failed(message);
                        messages.Add(message);
                    }

                    var reply = args.GetProperty("reply").GetString();
                    if (reply != null)
                    {
                        var added = await service.AddStaffCommentAsync(ctx.CompanyId, id, ctx.UserId, ctx.UserName, reply,
                            args.GetProperty("isInternal").GetBoolean());
                        if (!added) return AssistantActionResult.Failed("The message could not be added.");
                        messages.Add("Message added.");
                    }

                    return new AssistantActionResult { Ok = true, Message = string.Join(" ", messages), Reference = number, Link = $"/ServiceRequests/Details/{id}" };
                }
            };
        }

        /// <summary>Contracts, cheques and supplier bills: the day-to-day data entry.</summary>
        public static IEnumerable<AssistantTool> DataEntry()
        {
            // ---------------------------------------------------------------- draft contract
            yield return new AssistantTool
            {
                Name = "propose_create_lease",
                Description = "Prepare a new DRAFT tenancy contract. Collect tenant, unit, start date, annual rent and payment frequency first (ask the user for anything missing). Saved as a draft when confirmed; then offer propose_submit_lease.",
                Screen = ("Leases", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("tenant", Schema.Str("Tenant code or name; create the tenant first if new"), true),
                    ("unit", Schema.Str("Unit number/code"), true),
                    ("start_date", Schema.Date("First day of the contract"), true),
                    ("end_date", Schema.Date("Last day; default one year less a day"), false),
                    ("annual_rent", Schema.Num("Annual rent; default the unit's standard rent"), false),
                    ("billing_frequency_months", Schema.Int("Months per instalment: 1, 2, 3, 4, 6 or 12 (12 = one cheque)"), true),
                    ("security_deposit", Schema.Num("Security deposit, default 0"), false),
                    ("notes", Schema.Str("Notes"), false)),
                Propose = async (ctx, args) =>
                {
                    var (tenant, tenantError) = await AssistantReadTools.ResolveTenantAsync(ctx.Db, Args.Required(args, "tenant"));
                    if (tenant == null) return AssistantProposal.Refused(tenantError!);
                    var (unit, unitError) = await ResolveUnitAsync(ctx.Db, Args.Required(args, "unit"));
                    if (unit == null) return AssistantProposal.Refused(unitError!);

                    var start = Args.Date(args, "start_date") ?? throw new AssistantArgumentException("'start_date' is required.");
                    var model = new LeaseCreateViewModel
                    {
                        TenantId = tenant.Id,
                        UnitId = unit.Id,
                        StartDate = start,
                        EndDate = Args.Date(args, "end_date") ?? start.AddYears(1).AddDays(-1),
                        AnnualRent = Args.Dec(args, "annual_rent") ?? unit.StandardAnnualRent,
                        BillingFrequencyMonths = Args.Int(args, "billing_frequency_months") ?? 1,
                        SecurityDepositAmount = Args.Dec(args, "security_deposit") ?? 0m,
                        Notes = Args.Str(args, "notes")
                    };
                    if (model.AnnualRent <= 0) return AssistantProposal.Refused("Give the annual rent.");

                    var service = ctx.Get<LeaseCreationService>();
                    var errors = await service.ValidateAsync(ctx.CompanyId, model);
                    if (errors.Count > 0) return AssistantProposal.Refused(string.Join(" ", errors.Select(e => e.Message)));

                    var vat = await service.DerivedVatCategoryAsync(unit.Id, model.StartDate);
                    var instalments = 12 / model.BillingFrequencyMonths;
                    var warnings = new List<string>();
                    if (unit.StandardAnnualRent > 0 && model.AnnualRent < unit.StandardAnnualRent)
                        warnings.Add($"The rent is below the unit's standard rent of {unit.StandardAnnualRent:N2} {ctx.Currency}.");
                    if (unit.Status != "Vacant")
                        warnings.Add($"The unit is currently marked {unit.Status}.");

                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Draft contract for {tenant.Code} {tenant.FullName}, unit {unit.Property?.Code}/{unit.UnitNumber}, " +
                                  $"{model.StartDate:dd/MM/yyyy} to {model.EndDate:dd/MM/yyyy}, rent {model.AnnualRent:N2} {ctx.Currency} a year " +
                                  $"in {instalments} instalment(s) of {model.AnnualRent / instalments:N2}, deposit {model.SecurityDepositAmount:N2}, VAT treatment {vat}. " +
                                  "The contract number is assigned when saved; it has no effect until approved or activated.",
                        Warnings = warnings,
                        Normalized = model
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var model = args.Deserialize<LeaseCreateViewModel>(Json)!;
                    var service = ctx.Get<LeaseCreationService>();
                    var errors = await service.ValidateAsync(ctx.CompanyId, model);
                    if (errors.Count > 0) return AssistantActionResult.Failed(string.Join(" ", errors.Select(e => e.Message)));

                    var lease = await service.CreateDraftAsync(ctx.CompanyId, ctx.UserId, model);
                    var needsApproval = await ctx.Get<LeaseWorkflowService>().ApprovalRequiredAsync();
                    return new AssistantActionResult
                    {
                        Ok = true, Reference = lease.ContractNumber, Link = $"/Leases/Edit/{lease.Id}",
                        Message = $"Draft contract {lease.ContractNumber} saved. Next: " +
                                  (needsApproval ? "send it for approval." : "activate it to raise its invoices.")
                    };
                }
            };

            // ---------------------------------------------------------------- receive PDCs
            yield return new AssistantTool
            {
                Name = "propose_receive_pdcs",
                Description = "Prepare receiving one or more post-dated cheques for a contract (e.g. 4 quarterly cheques). Each is recorded on the received date and cleared later. Ask for any missing cheque number, date or amount.",
                Screen = ("PdcReceipts", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("contract", Schema.Str("Contract number"), true),
                    ("bank", Schema.Str("Bank the cheques are drawn on"), false),
                    ("received_date", Schema.Date("Date the cheques were handed over, default today"), false),
                    ("cheques", Schema.Array("The cheques",
                        Schema.Object(
                            ("cheque_number", Schema.Str("Cheque number"), true),
                            ("cheque_date", Schema.Date("Date written on the cheque"), true),
                            ("amount", Schema.Num("Amount"), true),
                            ("invoice_number", Schema.Str("Invoice it pays, if any; otherwise it is an advance"), false))), true)),
                Propose = async (ctx, args) =>
                {
                    var number = Args.Required(args, "contract");
                    var lease = await ctx.Db.Leases.Include(x => x.Tenant).FirstOrDefaultAsync(x => x.ContractNumber == number);
                    if (lease == null) return AssistantProposal.Refused($"No contract {number}.");
                    if (!args.TryGetProperty("cheques", out var cheques) || cheques.ValueKind != JsonValueKind.Array || cheques.GetArrayLength() == 0)
                        return AssistantProposal.Refused("List the cheques.");

                    var received = Args.Date(args, "received_date") ?? DateTime.Today;
                    var closed = await ClosedPeriodMessageAsync(ctx.Db, received, "A PDC receipt");
                    if (closed != null) return AssistantProposal.Refused(closed);

                    var bank = Args.Str(args, "bank");
                    var service = ctx.Get<PdcReceiptEntryService>();
                    var models = new List<PdcReceiptCreateViewModel>();
                    var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                    foreach (var cheque in cheques.EnumerateArray().Take(24))
                    {
                        var model = new PdcReceiptCreateViewModel
                        {
                            LeaseId = lease.Id,
                            ChequeNumber = Args.Required(cheque, "cheque_number"),
                            BankName = bank,
                            ChequeDate = Args.Date(cheque, "cheque_date") ?? throw new AssistantArgumentException("Each cheque needs its date."),
                            ReceivedDate = received,
                            Amount = Args.Dec(cheque, "amount") ?? 0m,
                            SettlementMode = "Advance"
                        };

                        var invoiceNumber = Args.Str(cheque, "invoice_number");
                        if (invoiceNumber != null)
                        {
                            var invoiceId = await ctx.Db.CustomerInvoices.Where(x => x.InvoiceNumber == invoiceNumber).Select(x => (int?)x.Id).FirstOrDefaultAsync();
                            if (invoiceId == null) return AssistantProposal.Refused($"No invoice {invoiceNumber}.");
                            model.CustomerInvoiceId = invoiceId;
                            model.SettlementMode = "Receivable";
                        }

                        if (!seen.Add(model.ChequeNumber))
                            return AssistantProposal.Refused($"Cheque {model.ChequeNumber} is listed twice.");
                        var errors = await service.ValidateAsync(ctx.CompanyId, model);
                        if (errors.Count > 0)
                            return AssistantProposal.Refused($"Cheque {model.ChequeNumber}: " + string.Join(" ", errors.Select(e => e.Message)));
                        models.Add(model);
                    }

                    var total = models.Sum(x => x.Amount);
                    var warnings = new List<string>();
                    var instalments = lease.BillingFrequencyMonths > 0 ? 12 / lease.BillingFrequencyMonths : 1;
                    if (lease.AnnualRent > 0 && models.Count == instalments && Math.Abs(total - lease.AnnualRent) > 1m)
                        warnings.Add($"The cheques total {total:N2} but the annual rent is {lease.AnnualRent:N2} (VAT or other charges may explain it).");

                    var list = string.Join("; ", models.Select(m => $"#{m.ChequeNumber} dated {m.ChequeDate:dd/MM/yyyy} {m.Amount:N2}" +
                                                                    (m.SettlementMode == "Receivable" ? " against an invoice" : " as advance")));
                    return new AssistantProposal
                    {
                        Ok = true,
                        Summary = $"Receive {models.Count} cheque(s) from {lease.Tenant?.FullName} for contract {lease.ContractNumber}, " +
                                  $"{bank ?? "bank not given"}, received {received:dd/MM/yyyy}, total {total:N2} {ctx.Currency}: {list}. " +
                                  "They are held as PDCs on hand; the tenant's balance changes only when each is cleared.",
                        Warnings = warnings,
                        Normalized = models
                    };
                },
                Execute = async (ctx, args) =>
                {
                    var models = args.Deserialize<List<PdcReceiptCreateViewModel>>(Json)!;
                    var service = ctx.Get<PdcReceiptEntryService>();
                    var done = new List<string>();
                    foreach (var model in models)
                    {
                        var errors = await service.ValidateAsync(ctx.CompanyId, model);
                        if (errors.Count > 0)
                            return AssistantActionResult.Failed(Partial(done) + $"Cheque {model.ChequeNumber}: " + string.Join(" ", errors.Select(e => e.Message)));
                        try
                        {
                            var result = await service.CreateAsync(ctx.CompanyId, model);
                            done.Add(result.Pdc.ChequeNumber + (result.NotPostedReason != null ? " (draft: " + result.NotPostedReason + ")" : string.Empty));
                        }
                        catch (Exception ex)
                        {
                            return AssistantActionResult.Failed(Partial(done) + $"Cheque {model.ChequeNumber} was not saved: {ex.Message}");
                        }
                    }

                    return new AssistantActionResult
                    {
                        Ok = true, Reference = string.Join(", ", models.Select(m => m.ChequeNumber)), Link = "/PdcReceipts",
                        Message = $"{done.Count} cheque(s) received: {string.Join(", ", done)}."
                    };
                }
            };

            // ---------------------------------------------------------------- vendor bill
            yield return new AssistantTool
            {
                Name = "propose_vendor_bill",
                Description = "Prepare a DRAFT supplier bill: vendor, their invoice number, date, due date and the lines with expense account and amount before VAT. Saved as a draft for review and posting on the Vendor Bills screen.",
                Screen = ("VendorBills", "Create"),
                IsWrite = true,
                Parameters = Schema.Object(
                    ("vendor", Schema.Str("Vendor code or name"), true),
                    ("vendor_reference", Schema.Str("The supplier's own invoice number"), false),
                    ("bill_date", Schema.Date("Date on the supplier's invoice"), true),
                    ("due_date", Schema.Date("Due date, default the bill date"), false),
                    ("property", Schema.Str("Property code it relates to, if any"), false),
                    ("category", Schema.Str("Expense category, e.g. Maintenance, Utilities"), false),
                    ("lines", Schema.Array("Bill lines",
                        Schema.Object(
                            ("description", Schema.Str("What was supplied"), true),
                            ("account", Schema.Str("Expense account code"), true),
                            ("amount", Schema.Num("Amount before VAT"), true),
                            ("vat", Schema.Bool("VAT charged on this line (default true if the vendor is VAT registered)"), false))), true)),
